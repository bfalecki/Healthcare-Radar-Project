% Generated by ChatGPT
% 2. Referencja tętna (parsowanie poprawne)

ref_heartbeat_path  = "reference" + filesep + "Phaser rec 1.09 19_20.txt";
rawT = readtable(ref_heartbeat_path, 'Delimiter','\n', 'ReadVariableNames', false);

% Rozdziel kolumny spacjami
parts = split(rawT.Var1);

% Usunięcie pustych kolumn (bo między danymi są podwójne spacje)
parts = parts(:, all(parts~=""));

% Teraz:
% parts(:,1) -> numer uderzenia
% parts(:,2) -> czas absolutny (hh:mm.ss)
% parts(:,3) -> odstęp między uderzeniami (IBI)

beat_idx   = str2double(parts(:,1));
time_str   = parts(:,2);
ibi_str    = parts(:,3);

% Zamiana czasu na sekundy
beat_times = seconds(duration(time_str,'InputFormat','mm:ss.SS'));

% Inter-beat intervals (IBI)
ibi = seconds(duration(string(ibi_str),'InputFormat', "mm:ss.SS"));     % [s]
inst_HR = 60 ./ ibi;           % [BPM]
t_HR = beat_times;             % czas dla każdego beatu

% Interpolacja do osi czasu (np. co 0.1 s)
t_uniform = 0:0.1:max(beat_times);
HR_uniform = interp1(t_HR, inst_HR, t_uniform, 'linear', 'extrap');

% Wykres
figure;
plot(t_HR, inst_HR, 'o-', 'DisplayName',"Beat-to-beat HR"); hold on;
plot(t_uniform, HR_uniform, '-', 'LineWidth',1.5, 'DisplayName',"Interpolated HR");
xlabel("Time [s]");
ylabel("Heart Rate [BPM]");
title("Reference heart rate from stopwatch");
legend show; grid on;